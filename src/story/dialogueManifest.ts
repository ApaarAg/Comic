type RawLineInput = Omit<
  DialogueLine,
  | 'bubblePosition'
  | 'characterFocus'
  | 'duration'
  | 'voiceAsset'
  | 'mode'
  | 'sourceOrigin'
  | 'animation'
> & {
  panelTarget?: string;
  mode?: DialoguePresentationMode;
  sourceOrigin?: DialogueSourceOrigin;
  characterFocus?: CharacterId;
  bubblePosition?: BubbleAnchorSide;
  animation?: DialogueAnimationSpec;
  wordTimings?: ReadonlyArray<WordTimingEntry>;
};

function defineLine(raw: RawLineInput): DialogueLine {
  const mode: DialoguePresentationMode =
    raw.mode ?? (raw.speaker === 'narrator' || raw.speaker === 'girl' ? 'narrator' : 'dialogue');
  const defaultEntrance: DialogueAnimationSpec['entrance'] =
    mode === 'narrator'
      ? 'caption'
      : raw.speaker === 'god' || raw.speaker === 'pranah'
        ? 'celestial'
        : raw.speaker === 'munmun'
          ? 'spectral'
          : 'ink';

  return {
    ...raw,
    mode,
    sourceOrigin: raw.sourceOrigin ?? 'comic',
    characterFocus: raw.characterFocus ?? raw.speaker,
    bubblePosition: raw.bubblePosition ?? raw.side,
    duration: Math.round((raw.durationMs / 1000) * 100) / 100,
    voiceAsset: raw.audioSrc,
    animation: raw.animation ?? {
      entrance: defaultEntrance,
      emphasizeSpeaker: mode === 'dialogue',
    },
  };
}

