import type { WordTimingEntry } from './scrollMath';

export type CharacterId =
  | 'narrator'
  | 'mrs_shah'
  | 'driver'
  | 'dhiraj'
  | 'girl'
  | 'death'
  | 'agni'
  | 'god'
  | 'munmun'
  | 'laila'
  | 'security'
  | 'pranah';

export type BubbleAnchorSide = 'left' | 'right' | 'center' | 'bottom';
export type CharacterExpression =
  | 'neutral'
  | 'urgent'
  | 'contemplative'
  | 'commanding'
  | 'shocked'
  | 'grief'
  | 'spectral'
  | 'warm';

export type DialoguePresentationMode = 'dialogue' | 'narrator' | 'narration';
export type DialogueSourceOrigin = 'comic' | 'connective';

export interface DialogueAnimationSpec {
  entrance: 'ink' | 'celestial' | 'spectral' | 'caption';
  emphasizeSpeaker?: boolean;
}

export interface DialogueLine {
  id: string;
  sceneId: string;
  sequenceId: string;
  mode: DialoguePresentationMode;
  sourceOrigin: DialogueSourceOrigin;
  speaker: CharacterId;
  speakerLabel: string;
  text: string;
  side: BubbleAnchorSide;
  bubblePosition: BubbleAnchorSide;
  characterFocus: CharacterId;
  expression: CharacterExpression;
  /** Panel image filename or selector this line is anchored to */
  panelTarget?: string;
  /** Scroll trigger progress [0..1] within the enclosing dialogue stage */
  triggerProgress: number;
  /** Duration in seconds for voice playback or honest visual cadence timing */
  duration: number;
  /** Duration in ms derived cleanly for existing callers */
  durationMs: number;
  /** Structured audio asset path under /assets/audio/voices/<character>/ */
  audioSrc: string;
  /** Legacy alias kept in sync with audioSrc */
  voiceAsset?: string;
  /** Optional explicit word-level timestamps when studio recordings include forced alignment */
  wordTimings?: ReadonlyArray<WordTimingEntry>;
  animation: DialogueAnimationSpec;
  /** Optional SFX cue fired when this dialogue beat enters */
  sfxCue?: 'bubble' | 'ding' | 'horn' | 'thunder' | 'flatline' | 'truck' | 'discover';
}

